import pytest

from law_links.chains import tokenize, value_text


def chain(chains, text):
    found = chains.find(text)
    assert len(found) == 1, found
    c = found[0]
    return c.articles, c.points, c.subpoints


@pytest.mark.parametrize(
    "text, expected",
    [
        ("пп. 1 п. 1 ст. 374", (["374"], ["1"], ["1"])),
        ("подпункту 2 пунта б статьи 22", (["22"], ["б"], ["2"])),
        ("в подпунктах а, б и с пункта 3.345, 23 в статье 66", (["66"], ["3.345", "23"], ["а", "б", "с"])),
        ("часть 3, ст. 30.1", (["30.1"], ["3"], [])),
        ("Согласно п.  10 АПК", ([], ["10"], [])),
        ("ст. 30 и в соответствии", (["30"], [], [])),
        # constructions from court decisions
        ("по ч. 1 ст. 19.5. КоАП РФ", (["19.5"], ["1"], [])),
        ("в силу п. «б» ч. 1 ст. 58 УК РФ", (["58"], ["1"], ["б"])),
        ("на основании п. 6 ч. 1 ст. 24.5 КоАП РФ", (["24.5"], ["1"], ["6"])),
        ('подпунктом "г" пункта 6 части 1 статьи 81 Трудового кодекса', (["81"], ["6"], ["г"])),
        ("пункту 1 части первой статьи 81 ТК РФ", (["81"], ["1"], ["1"])),
        ("руководствуясь ст.ст. 194 -199 ГПК РФ", (["194-199"], [], [])),
        ("согласно абз. 1 ст. 394 ТК РФ", (["394"], [], [])),
        ("как ч.1, так и ч.24 ст.19.5 КоАП РФ", (["19.5"], ["1", "24"], [])),
        # the article first
        ("Статья 20.4 ч. 1 КоАП РФ, предусматривает", (["20.4"], ["1"], [])),
        ("статья 30.7 часть 1 пункт 3 КоАП РФ", (["30.7"], ["1"], ["3"])),
        ("по ст. 105 ч. 2 п. «а» УК РФ", (["105"], ["2"], ["а"])),
    ],
)
def test_chain(chains, text, expected):
    assert chain(chains, text) == expected


@pytest.mark.parametrize(
    "text",
    [
        "пост 5 и степ 6",
        "характеризуется удовлетворительно (л.д. 55-61), что",
        "по адресу: ст. Отрадная, ул. Широкая",
        "по правилам соответствующей главы части второй Кодекса",
        # no marker word: numbers of a table, volume and sheet of a case file
        "5 264 687,74 01.01.2024 28.07.2024 210 16 5 264 687,74",
        "(т. 10, л.д. 100-111) - материалы",
    ],
)
def test_no_chain(chains, text):
    assert chains.find(text) == []


@pytest.mark.parametrize(
    "text, expected",
    [
        # glued words
        ("В соответствии спп. 1 п. 1 ст. 374 НК РФ", (["374"], ["1"], ["1"])),
        ("положенийч. 6ст. 15 УК РФ", (["15"], ["6"], [])),
        ("Согласностатье 16 Закона", (["16"], [], [])),
        # Latin look-alike letters
        ("согласно cт. 30 ГК РФ", (["30"], [], [])),
        # typos in markers
        ("пункт 1 сттаьи 114 НК РФ", (["114"], ["1"], [])),
        ("по пбнкту 1 чсти 1 статьи 81 ТК РФ", (["81"], ["1"], ["1"])),
        # dots
        ("на основании ст. ст. 8, 9, 486, 487., 516., 1102 ГК РФ", (["8", "9", "486", "487", "516", "1102"], [], [])),
        ("установленные ч. 2.3. ст..161 ЖК РФ", (["161"], ["2.3"], [])),
        # the marker right before the chain is tagged O
        ("для целей статей 228, 228.1 УК РФ", (["228", "228.1"], [], [])),
    ],
)
def test_noisy_chain(chains, text, expected):
    assert chain(chains, text) == expected


def test_glued_split_needs_a_number():
    assert [t.text for t in tokenize("текст песни, участи 5")] == ["текст", "песни", ",", "участи", "5"]


def test_value_text():
    assert value_text("43.2 - 6") == "43.2-6"
    assert value_text("первой") == "1"
    assert [t.text for t in tokenize("ст.ст. 19.5.")] == ["ст", ".", "ст", ".", "19.5", "."]


def test_article_first_and_enumerations(chains):
    def found(text):
        return [(c.articles, c.points, c.subpoints) for c in chains.find(text)]

    assert found("ст. 12.8 ч. 1, ст. 12.26 ч. 2 КоАП РФ") == [(["12.8"], ["1"], []), (["12.26"], ["2"], [])]
    assert found("ч. 6 ст. 15 ч. 2 ст. 64 УК РФ") == [(["15"], ["6"], []), (["64"], ["2"], [])]
    assert found("пунктами «а», «б» части 2 статьи 105 УК") == [(["105"], ["2"], ["а", "б"])]
